public class ExemploParOuImpar {
    public static void main(String[] args) {

        for (int i = 100; i <= 1000; i++) {
            if (i % 2 == 0) {
                System.out.println(i + " número par");

            } else {
                System.out.println(i + " número ímpar");
            }
        }

    }
}
